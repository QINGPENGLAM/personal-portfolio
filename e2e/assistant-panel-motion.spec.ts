import { expect, test } from '@playwright/test'

test('animates opening/closing, returns focus and retains the draft', async ({ page }) => {
  await page.goto('/personal-portfolio/')
  const toggle = page.getByRole('button', { name: 'Ask portfolio', exact: true })
  await toggle.click()
  const panel = page.locator('#portfolio-assistant-panel')
  expect(await panel.evaluate(node => node.getAnimations().length)).toBeGreaterThan(0)
  await panel.evaluate(node => Promise.all(node.getAnimations().map(animation => animation.finished)))
  await expect(page.getByRole('textbox')).toBeFocused()
  await page.getByRole('textbox').fill('What is his GPA?')
  await page.keyboard.press('Escape')
  await expect(panel).toHaveCount(0)
  await expect(toggle).toBeFocused()
  await toggle.click()
  await panel.evaluate(node => Promise.all(node.getAnimations().map(animation => animation.finished)))
  await expect(page.getByRole('textbox')).toHaveValue('What is his GPA?')
})
test('keeps an inert exit panel until the fallback completes when animation is interrupted', async ({ page }) => {
  await page.goto('/personal-portfolio/')
  await page.getByRole('button', { name: 'Ask portfolio', exact: true }).click()
  const panel = page.locator('#portfolio-assistant-panel')
  await page.addStyleTag({ content: '.assistant-panel { animation: none !important; }' })
  await page.clock.install()
  await page.getByRole('button', { name: 'Close portfolio guide' }).click()
  await expect(panel).toHaveAttribute('aria-hidden', 'true')
  await expect(panel).toHaveAttribute('inert', '')
  await page.clock.runFor(100)
  await page.keyboard.press('Escape')
  await page.clock.runFor(200)
  await expect(panel).toHaveCount(0)
  await page.clock.runFor(20)
  await expect(page.getByRole('button', { name: 'Ask portfolio', exact: true })).toBeFocused()
})
test('skips opening/closing motion and close timers with reduced motion', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/personal-portfolio/')
  const toggle = page.getByRole('button', { name: 'Ask portfolio', exact: true })
  await toggle.click()
  const panel = page.locator('#portfolio-assistant-panel')
  expect(await panel.evaluate(node => node.getAnimations().length)).toBe(0)
  await page.clock.install()
  await page.keyboard.press('Escape')
  await expect(panel).toHaveCount(0)
  await page.clock.runFor(20)
  await expect(toggle).toBeFocused()
})
