for (const colorScheme of ['dark', 'light'] as const) {
  test(`keeps the explorer accessible in ${colorScheme} mode`, async ({ page }, testInfo) => {
    test.skip(testInfo.project.name !== 'chromium', 'Run scoped semantic checks once per theme.')
    await page.emulateMedia({ colorScheme, reducedMotion: 'reduce' })
    await page.goto('/skills/')
    await expect(page.getByRole('button', { name: `Switch to ${colorScheme === 'dark' ? 'day' : 'night'} theme` })).toBeVisible()
    const results = await new AxeBuilder({ page }).include('[aria-label="Skill evidence explorer"]').withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
    expect(results.violations.filter(item => item.impact === 'critical' || item.impact === 'serious').map(item => ({ id: item.id, nodes: item.nodes.map(node => node.target) }))).toEqual([])
  })
}
